// Trains the 2 → 8 → 8 → 2 network used on the page and prints its weights as
// a TypeScript module. Not imported by the page: the weights are fixed in
// weights.ts so that every bound in the figures is the same on every machine.
//
//   npx --no-install tsx components/verification/train.ts > components/verification/weights.ts
//
// Plain full-batch Adam on cross-entropy, seeded, no regularisation.
import { moons, rng } from "./data";

const SIZES = [2, 8, 8, 2];
const SEED = 7;
const STEPS = 6000;
const LR = 0.01;

const rand = rng(SEED);
const data = moons(160, 0.12, SEED);

// He-style initialisation
const W: Float64Array[] = [];
const B: Float64Array[] = [];
for (let k = 0; k + 1 < SIZES.length; k++) {
  const fanIn = SIZES[k];
  const w = new Float64Array(SIZES[k + 1] * fanIn);
  for (let i = 0; i < w.length; i++) {
    const g = Math.sqrt(-2 * Math.log(1 - rand())) * Math.cos(2 * Math.PI * rand());
    w[i] = g * Math.sqrt(2 / fanIn);
  }
  W.push(w);
  B.push(new Float64Array(SIZES[k + 1]));
}

const params = [...W, ...B];
const m1 = params.map((p) => new Float64Array(p.length));
const m2 = params.map((p) => new Float64Array(p.length));

for (let step = 1; step <= STEPS; step++) {
  const gW = W.map((w) => new Float64Array(w.length));
  const gB = B.map((b) => new Float64Array(b.length));
  let loss = 0;
  for (let s = 0; s < data.length; s++) {
    const { x, y } = data[s];
    // forward, keeping every layer's activations
    const acts: Float64Array[] = [Float64Array.from(x)];
    const pres: Float64Array[] = [];
    for (let k = 0; k < W.length; k++) {
      const a = acts[k];
      const n = SIZES[k + 1];
      const z = new Float64Array(n);
      for (let i = 0; i < n; i++) {
        let v = B[k][i];
        for (let j = 0; j < a.length; j++) v += W[k][i * a.length + j] * a[j];
        z[i] = v;
      }
      pres.push(z);
      acts.push(k + 1 < W.length ? z.map((v) => Math.max(0, v)) : z);
    }
    const z = acts[acts.length - 1];
    const mx = Math.max(z[0], z[1]);
    const e0 = Math.exp(z[0] - mx);
    const e1 = Math.exp(z[1] - mx);
    const p = [e0 / (e0 + e1), e1 / (e0 + e1)];
    loss -= Math.log(p[y]);
    // backward
    let d = new Float64Array([p[0] - (y === 0 ? 1 : 0), p[1] - (y === 1 ? 1 : 0)]);
    for (let k = W.length - 1; k >= 0; k--) {
      const a = acts[k];
      for (let i = 0; i < d.length; i++) {
        gB[k][i] += d[i];
        for (let j = 0; j < a.length; j++) gW[k][i * a.length + j] += d[i] * a[j];
      }
      if (k === 0) break;
      const prev = new Float64Array(a.length);
      for (let j = 0; j < a.length; j++) {
        if (pres[k - 1][j] <= 0) continue;
        let v = 0;
        for (let i = 0; i < d.length; i++) v += W[k][i * a.length + j] * d[i];
        prev[j] = v;
      }
      d = prev;
    }
  }
  const grads = [...gW, ...gB];
  const b1 = 0.9;
  const b2 = 0.999;
  for (let q = 0; q < params.length; q++) {
    for (let i = 0; i < params[q].length; i++) {
      const g = grads[q][i] / data.length;
      m1[q][i] = b1 * m1[q][i] + (1 - b1) * g;
      m2[q][i] = b2 * m2[q][i] + (1 - b2) * g * g;
      const mh = m1[q][i] / (1 - Math.pow(b1, step));
      const vh = m2[q][i] / (1 - Math.pow(b2, step));
      params[q][i] -= (LR * mh) / (Math.sqrt(vh) + 1e-8);
    }
  }
  if (step % 1000 === 0) console.error(`step ${step}  loss ${(loss / data.length).toFixed(4)}`);
}

const r = (a: Float64Array) => `[${Array.from(a, (v) => +v.toFixed(4)).join(", ")}]`;
console.log(`// Generated by train.ts (seed ${SEED}, ${STEPS} steps of Adam on two moons). Do not edit by hand.
import type { Net } from "./net";

export const NET: Net = {
  sizes: [${SIZES.join(", ")}],
  W: [
${W.map((w) => `    ${r(w)},`).join("\n")}
  ],
  b: [
${B.map((b) => `    ${r(b)},`).join("\n")}
  ],
};`);
